export type IconName = keyof typeof REGISTRY;

export interface IconProps {
  name: IconName;
  size?: number;
  tone?: IconTone;
  strokeWidth?: number;
  className?: string;
  style?: CSSProperties;
  filled?: boolean;
  title?: string;
}

export function Icon({
  name,
  size = 20,
  tone = 'inherit',
  strokeWidth = 1.75,
  className = '',
  style,
  filled = false,
  title,
}: IconProps) {
  const Glyph = REGISTRY[name];
  return (
    <Glyph
      width={size}
      height={size}
      strokeWidth={strokeWidth}
      fill={filled ? 'currentColor' : 'none'}
      color={TONE_VAR[tone]}
      className={`shrink-0 ${className}`.trim()}
      style={style}
      aria-hidden={title ? undefined : true}
      aria-label={title}
      role={title ? 'img' : undefined}
    />
  );
}

